export const DICTS: Record<Lang, Dict> = { ru, cs, en };
export type MessageKey = keyof typeof ru;

export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? DICTS.ru[key] ?? key;
  if (vars) Object.entries(vars).forEach(([k, v]) => (s = s.replaceAll(`{${k}}`, String(v))));
  return s;
}

const LOCALES: Record<Lang, string> = { ru: 'ru-RU', cs: 'cs-CZ', en: 'en-GB' };

interface I18n {
  lang: Lang;
  setLang(l: Lang): void;
  t(key: MessageKey, vars?: Record<string, string | number>): string;
  date(iso: string | null): string;
  /** Calendar date without time, for deadlines (yyyy-mm-dd). */
  day(iso: string | null): string;
  money(v: number | null | undefined, currency?: string | null): string;
  num(v: number | null | undefined, digits?: number): string;
}

const Ctx = createContext<I18n | null>(null);

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('dealos.lang') as Lang | null;
    if (saved && LANGS.includes(saved)) return saved;
  } catch {
    /* storage unavailable */
  }
  return 'ru';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const value = useMemo<I18n>(() => ({
    lang,
    setLang: (l) => {
      setLangState(l);
      try { localStorage.setItem('dealos.lang', l); } catch { /* ignore */ }
    },
    t: (key, vars) => translate(lang, key, vars),
    date: (iso) => (iso ? new Intl.DateTimeFormat(LOCALES[lang], {
      day: 'numeric', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit',
    }).format(new Date(iso)) : ''),
    day: (iso) => (iso ? new Intl.DateTimeFormat(LOCALES[lang], { day: 'numeric', month: 'short', year: 'numeric' })
      .format(new Date(`${iso.slice(0, 10)}T12:00:00`)) : ''),
    money: (v, currency) => (v == null ? '—' : currency
      ? new Intl.NumberFormat(LOCALES[lang], { style: 'currency', currency, minimumFractionDigits: 2 }).format(v)
      : new Intl.NumberFormat(LOCALES[lang], { minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(v)),
    num: (v, digits = 2) => (v == null ? '—'
      : new Intl.NumberFormat(LOCALES[lang], { maximumFractionDigits: digits }).format(v)),
  }), [lang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error('useI18n outside I18nProvider');
  return v;
}
